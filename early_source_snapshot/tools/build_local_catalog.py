    # 1. Exact published ТХК cards.
    tirhleb = json.loads((ROOT / 'tools/data/tirhleb_products.json').read_text(encoding='utf-8'))
    for row in tirhleb:
        name = row['name'].strip()
        category = category_for_tirhleb(name)
        brand = 'ЗАО «Тираспольский хлебокомбинат» (ТХК)'
        note = ('По официальному каталогу ТХК; БЖУ на 100 г. '
                'Микронутриенты — ориентир по категории. Сверьте упаковку.')
        keywords = ' '.join([
            'тхк тираспольский хлебокомбинат хлеб выпечка пмр',
            brand, name, name.replace('«','').replace('»',''), category,
        ])
        records.append(make_record(
            name, row['calories'], row['protein'], row['fat'], row['carbs'],
            category, brand, row['sourceUrl'], note, keywords, 'label',
        ))

    # 2. Major PMR producers and their typical product lines.
    for short, full, categories, region, aliases in PRODUCERS:
        generated = 0
        for category in categories:
            templates = TEMPLATES.get(category, [])
            # Keep the list useful without drowning the user in duplicates.
            limit = 6 if len(categories) == 1 else 3
            for tpl in templates[:limit]:
                name0, cal, protein, fat, carbs, tpl_kw = tpl
                name = f'{name0} [{short}]'
                note = ('Ориентировочно по категории; точные БЖУ сверьте с упаковкой. '
                        'Производитель указан по официальному перечню производителей ПМР. '
                        'Микронутриенты — ориентир по категории.')
                keywords = ' '.join([
                    name0, name, short, full, aliases, region, 'пмр приднестровье',
                    category, tpl_kw,
                ])
                records.append(make_record(
                    name, cal, protein, fat, carbs, category, full,
                    PMR_LIST_URL, note, keywords, 'typical',
                ))
                generated += 1
        # ТХК already has 94 exact cards; add only its drinks from the generic list.
        if short == 'ТХК':
            for tpl in TEMPLATES['Напитки']:
                name0, cal, protein, fat, carbs, tpl_kw = tpl
                name = f'{name0} [ТХК]'
                note = ('Ориентировочно по категории напитков ТХК; сверьте упаковку. '
                        'Предприятие также официально производит воду и напитки.')
                keywords = ' '.join([name0, name, 'тхк вода напитки пмр', tpl_kw])
                records.append(make_record(
                    name, cal, protein, fat, carbs, 'Напитки',
                    'ЗАО «Тираспольский хлебокомбинат» (ТХК)',
                    TIRHLEB_CATALOG_URL, note, keywords, 'typical',
                ))

    OUT_JSON.parent.mkdir(parents=True, exist_ok=True)
    OUT_JSON.write_text(json.dumps({
        'version': 1,
        'generatedBy': 'tools/build_local_catalog.py',
        'sourceLabel': 'Продукция ПМР',
        'sourceUrls': [PMR_LIST_URL, TMK_URL, BLAGODA_URL, TIRHLEB_CATALOG_URL],
        'producers': [p[0] for p in PRODUCERS],
        'count': len(records),
        'labelQualityCount': sum(1 for r in records if r['quality'] == 'label'),
        'items': records,
    }, ensure_ascii=False, indent=2), encoding='utf-8')

    lines = [
        '// GENERATED FILE — DO NOT EDIT BY HAND.',
        '// Regenerate with: python3 tools/build_local_catalog.py',
        "import '../legacy.dart';",
        "import 'engine.dart';",
        '',
        '/// Offline PMR / CIS catalog. All product names are Cyrillic.',
        '/// Exact ТХК values come from its official catalog; other rows are',
        '/// category estimates and are labelled as such in `note`.',
        'const List<FoodItem> localCatalogFoods = <FoodItem>[',
    ]
    for r in records:
        micro_literal = ', '.join(f'{q(k)}: {dart_double(v)}' for k, v in r['micros'].items())
        lines.append('  FoodItem(')
        lines.append(f'    {q(r["name"])},')
        for field in ['calories', 'protein', 'fat', 'carbs']:
            lines.append(f'    {dart_double(r[field])},')
        lines.append(f'    const <String, double>{{{micro_literal}}},')
        lines.append(f'    {q(r["category"])},')
        lines.append('    pmrSource,')
        lines.append(f'    {q(r["brand"])},')
        lines.append(f'    {nullable_q(r["barcode"])},')
        lines.append(f'    {q(r["note"])},')
        lines.append(f'    {q(r["sourceUrl"])},')
        lines.append(f'    {q(r["keywords"])},')
        lines.append('  ),')
    lines.append('];')
    lines.append('')
    OUT_DART.write_text('\n'.join(lines), encoding='utf-8')
    print(f'Wrote {len(records)} local products from {len(PRODUCERS)} producers to {OUT_DART}')


