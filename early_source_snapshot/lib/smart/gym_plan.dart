import 'gym_models.dart';

class GymDayPlan {
  final String id, shortName, title, description, warmup, cardioPlan;
  final int weekday;
  final List<GymBlock> blocks;
  const GymDayPlan({
    required this.id,
    required this.shortName,
    required this.weekday,
    required this.title,
    required this.description,
    required this.warmup,
    required this.cardioPlan,
    required this.blocks,
  });

  GymSession start(String id, DateTime now) => GymSession.fromJson({
    'version': 1,
    'id': id,
    'planDay': this.id,
    'title': title,
    'startedAt': now.toUtc().toIso8601String(),
    'resumedAt': now.toUtc().toIso8601String(),
    'warmup': warmup,
    'cardioPlan': cardioPlan,
    'elapsedBaseSeconds': 0,
    'restLabel': '',
    'note': '',
    'blocks': blocks.map((e) => e.toJson()).toList(),
    'cardio': <Object>[],
  });
}

GymExercise _e(
  String id,
  String name,
  int sets,
  String target, {
  List<String> alternatives = const [],
  List<String> targets = const [],
  bool timed = false,
  bool test = false,
}) => GymExercise(
  id: id,
  name: name,
  plannedSets: sets,
  target: target,
  alternatives: List.of(alternatives),
  targets: List.of(targets),
  timed: timed,
  isTest: test,
);

GymBlock _b(
  String id,
  String title,
  int min,
  int max,
  List<GymExercise> exercises, {
  String note = '',
  bool optional = false,
}) => GymBlock(
  id: id,
  title: title,
  restMinSeconds: min,
  restMaxSeconds: max,
  exercises: exercises,
  note: note,
  optional: optional,
);

